@ontology_bp.route('/api/ontology/graph')
@login_required
def get_graph():
    limit = request.args.get('limit', 50, type=int)
    cust_id = request.args.get('customer_id', None)
    tx_id = request.args.get('transaction_id', None)
    entity_type = request.args.get('entity_type', None)

    builder = KnowledgeGraphBuilder(db.session)
    graph_data = builder.get_graph_data(limit=limit, customer_filter=cust_id, transaction_filter=tx_id, entity_type_filter=entity_type)
    return jsonify(graph_data)
